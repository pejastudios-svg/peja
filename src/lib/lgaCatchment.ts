/** Estimated population of an LGA, or null if we do not have it. */
export function catchmentFor(state: string, lga: string): number | null {
  return LGA_CATCHMENT[`${state}|${lga}`] ?? null;
}

/** "2.1 million people" / "420,000 people", for display next to a tier. */
export function formatCatchment(n: number): string {
  if (n >= 1_000_000) {
    const m = n / 1_000_000;
    return `${m >= 10 ? Math.round(m) : m.toFixed(1)} million`;
  }
  return n.toLocaleString();
}
